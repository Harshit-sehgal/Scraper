/**
 * Render an icon as an inline SVG string.
 * @param {string} name one of icon names in ICON_PATHS
 * @param {number} [size=16] width/height in pixels
 * @param {string} [extraClasses=\"\"] additional CSS classes (.icon-md / .icon-lg / etc.)
 * @returns {string} SVG markup
 */
export function icon(name, size = 16, extraClasses = "") {
  const paths = ICON_PATHS[name];
  if (!paths) {
    console.warn(`icons.js: unknown icon "${name}"`);
    return "";
  }
  const cls = `icon ${extraClasses}`.trim();
  const inner = paths.map((d) => `<path d="${d}"/>`).join("");
  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 256 256" fill="none" stroke="currentColor" stroke-width="12" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${inner}</svg>`;
}

export const ICON_NAMES = Object.keys(ICON_PATHS);

/**
 * Hydrate any [data-icon] element in `root` (default: document) with the
 * named icon SVG. Skips elements already containing an `<svg>`. The element's
 * `data-size` attribute (default 16) controls the rendered icon size.
 */
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    if (el.firstElementChild && el.firstElementChild.tagName === "svg") return;
    const name = el.getAttribute("data-icon");
    if (!name) return;
    const size = parseInt(el.dataset.size || "16", 10);
    el.innerHTML = icon(name, size);
  });
}

// Auto-hydrate any [data-icon] elements that get added to the DOM after
// boot — covers innerHTML rewrites inside views (renderJobs, renderResults,
// addField, addFilter, etc.) that re-inject data-icon placeholders without
// re-running a view-switch. Idempotent: hydrateIcons() skips already-hydrated
// elements (those whose firstElementChild is an <svg>).
let _observerStarted = false;
export function startIconObserver(target = document.body) {
  if (_observerStarted) return;
  _observerStarted = true;
  const mo = new MutationObserver((records) => {
    for (const r of records) {
      r.addedNodes.forEach((node) => {
        if (node.nodeType !== 1) return;
        if (node.matches?.("[data-icon]")) {
          if (!node.firstElementChild || node.firstElementChild.tagName !== "svg") {
            const name = node.getAttribute("data-icon");
            const size = parseInt(node.dataset.size || "16", 10);
            if (name) node.innerHTML = icon(name, size);
          }
        } else if (node.querySelectorAll) {
          node.querySelectorAll("[data-icon]").forEach((el) => {
            if (el.firstElementChild && el.firstElementChild.tagName === "svg") return;
            const name = el.getAttribute("data-icon");
            if (!name) return;
            const size = parseInt(el.dataset.size || "16", 10);
            el.innerHTML = icon(name, size);
          });
        }
      });
    }
  });
  mo.observe(target, { childList: true, subtree: true });
}
